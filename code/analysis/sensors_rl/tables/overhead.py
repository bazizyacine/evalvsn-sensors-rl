"""The costs table, the costs of the four stacks, of the control AOMDV and of
the access-only stack for a sensor node: the
radio energy of the network and per node, the control messages and the memory
the agents add to a node (analysis/overhead.py)."""
from ..analysis import overhead as oh
from ..compile import measures
from ..common.notation import fixed
from . import cells

HEAD = '% generated by code/analysis/sensors_rl/tables/overhead.py from data/sensors-rl/article/overhead.tsv and revision.tsv'
LABEL = {'pq': ('AOMDV', 'AOMDV'), 'pq-ctl': ('AOMDV de contrôle', 'Control AOMDV'),
         'rules': ('Règles', 'Rules'), 'access': ('Accès seul', 'Access only'), 'agents': ('Agents', 'Agents'),
         'hybrid': ('Hybride', 'Hybrid')}
GROUPS = {'fr': ('', '\\multicolumn{2}{c}{\\textbf{Énergie (J)}}', '\\multicolumn{3}{c}{\\textbf{Messages de contrôle}}', ''),
          'en': ('', '\\multicolumn{2}{c}{\\textbf{Energy (J)}}', '\\multicolumn{3}{c}{\\textbf{Control messages}}', '')}
# the busiest node's energy and the RREP count stay in the printed statistics only
COLUMNS = {'fr': ('Pile', 'Réseau', 'Par nœud', 'HELLO', 'RREQ', 'RERR', 'Mémoire (octets)'),
           'en': ('Stack', 'Network', 'Per node', 'HELLO', 'RREQ', 'RERR', 'Memory (bytes)')}
COLS = cells.xcols(('0.96', '1.02', '0.86', '0.76', '0.74', '1.66'), 'l', fill=True)
# the rows; overhead.tsv also holds AOMDV with cross-layer timers, which the
# report prints
ROWS = ('pq', 'pq-ctl', 'rules', 'access', 'agents', 'hybrid')


def num(x, nd, lang):
    return fixed(x, nd, lang, thousands=True)


def write(lang, en_rows, rev, routing, mem):
    out = [HEAD, cells.setup(lang),
           '\\begin{tabularx}{\\linewidth}{%s}' % COLS, '\\toprule',
           ' & '.join(GROUPS[lang]) + ' \\\\', '\\cmidrule(lr){2-3}\\cmidrule(lr){4-6}',
           ' & '.join('\\textbf{%s}' % h if h else '' for h in COLUMNS[lang]) + ' \\\\', '\\midrule']
    traced_arm = {stack: traced for stack, _, traced in measures.ENERGY_STACKS}
    body = []
    for stack in ROWS:
        e = oh.energy(en_rows, stack) or {}
        c = oh.control(stack, traced_arm[stack], rev, routing)
        row = [num(e.get('e_total'), 1, lang), num(e.get('e_node'), 2, lang)]
        row += [num(c[m], 0, lang) for m in ('hello', 'rreq_all', 'rerr')]
        row.append(num(float(mem[stack]['node']) if stack in mem else 0.0, 0, lang))
        body.append([LABEL[stack][0 if lang == 'fr' else 1]] + row)
    body = cells.align_rows(body, lang, range(1, 7))
    for r, after in zip(body, cells.rules(range(len(body)))):
        out += [' & '.join(r) + ' \\\\', after]
    out.append('\\end{tabularx}')
    return cells.write(lang, 'revision-couts', out)


def tables(langs):
    en_rows, rev, routing = oh.inputs()
    _, mem = oh.memory()
    return [write(lang, en_rows, rev, routing, mem) for lang in langs]
