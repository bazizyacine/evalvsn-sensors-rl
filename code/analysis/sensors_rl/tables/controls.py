"""The controls and decisions tables: the controls of the adaptation of the
agents (means over the 60 seeds at GOP 9-3, the policy of the agents written
once over its stacks), and each agent's decisions at the end of the traced
simulations (agent-trace.tsv). The second round adds to the controls the
crossing of learning and exploration on the hybrid stack, the
two levels of the link-break agent's exploration on the agents stack,
the access-only stack at the constant rate and, in one row, the four
configurations its agent learned, frozen. A value the 60
seeds do not all provide prints as a dash."""
from ..analysis import ablation, controls, round2
from ..common import data
from ..common.notation import plain
from . import cells

HEAD = '% generated by code/analysis/sensors_rl/tables/controls.py from data/sensors-rl/article/revision.tsv and round2.tsv'
HEAD_AGENTS = '% generated by code/analysis/sensors_rl/tables/controls.py from data/sensors-rl/article/agent-trace.tsv'
# The agents' policy in its own column, the stacks in the article's order
# (access only, agents, then hybrid) under each policy: the rule stack, which
# has no agent, first and alone; frozen (neither learning nor exploration,
# the initial choice kept), exploration only, learning only, the constant
# exploration of the main study (epsilon = 0.1); the configurations the
# access-only stack's agent learned in its four development runs, frozen,
# their mean in one row (LEARNED, its label on two lines); the decaying
# exploration; then the link-break agent alone without exploration or with
# its exploration decaying, the six other agents at the constant rate.
# (policy, arm, traced arm, stack)
LEARNED = 'learned'
POLICIES = {'fr': {'': 'sans agent', 'frozen': 'figée', 'explore': 'exploration seule ($\\nu = 0$)',
                   'learn': 'apprentissage seul ($\\varepsilon = 0$)', 'const': '$\\varepsilon$ constant',
                   LEARNED: cells.TWO_LINES % ('apprises, puis figées', '(4 configurations)'),
                   'edec': '$\\varepsilon$ décroissant', 'bgreedy': '$\\varepsilon = 0$, rupture seule',
                   'bdec': '$\\varepsilon$ décroissant, rupture seule'},
            'en': {'': 'no agent', 'frozen': 'frozen', 'explore': 'exploration only ($\\nu = 0$)',
                   'learn': 'learning only ($\\varepsilon = 0$)', 'const': 'constant $\\varepsilon$',
                   LEARNED: cells.TWO_LINES % ('learned, then frozen', '(4 configurations)'),
                   'edec': 'decaying $\\varepsilon$', 'bgreedy': '$\\varepsilon = 0$, link break only',
                   'bdec': 'decaying $\\varepsilon$, link break only'}}
ARMS = (('', 'rules', 'rules', 'rules'),
        ('frozen', 'agents-frozen', 'agents-frozen', 'agents'), ('frozen', 'hybrid-frozen', 'hybrid-frozen', 'hybrid'),
        ('explore', 'hybrid-explore-s11', 'hybrid-explore-s11', 'hybrid'),
        ('learn', 'hybrid-learn-s11', 'hybrid-learn-s11', 'hybrid'),
        ('const', ablation.ACCESS_ONLY, ablation.ACCESS_ONLY, 'access'),
        ('const', 'agents', 'agents-tr', 'agents'), ('const', 'hybrid', 'hybrid-tr', 'hybrid'),
        (LEARNED, LEARNED, LEARNED, 'access'),
        ('edec', 'agents-edec', 'agents-edec', 'agents'), ('edec', 'hybrid-edec', 'hybrid-edec', 'hybrid'),
        ('bgreedy', 'agents-bgreedy', 'agents-bgreedy', 'agents'), ('bdec', 'agents-bdec-s11', 'agents-bdec-s11', 'agents'))
STACK_NAMES = {'fr': {'rules': 'Règles', 'access': 'Accès seul', 'agents': 'Agents', 'hybrid': 'Hybride'},
               'en': {'rules': 'Rules', 'access': 'Access only', 'agents': 'Agents', 'hybrid': 'Hybrid'}}
COLUMNS = {'fr': ('Politique', 'Pile', 'PSNR (dB)', 'Perte M1 (\\%)', 'Perte (\\%)', cells.IMAGES, 'Décl.', 'RREQ', 'RERR'),
           'en': ('Policy', 'Stack', 'PSNR (dB)', 'M1 loss (\\%)', 'Loss (\\%)', cells.IMAGES, 'Decl.', 'RREQ', 'RERR')}
SEP = '4pt'
COLS = cells.xcols(('1.02', '1.24', '1.00', '1.34', '0.80', '0.80', '0.80'), 'll', fill=True)

AGENTS = (('path', 'hybrid', 'Chemin', 'Path'), ('congestion', 'hybrid', 'Congestion', 'Congestion'),
          ('access', 'hybrid', 'Accès au canal', 'Channel access'), ('discard', 'hybrid', 'Rejet anticipé', 'Early discard'),
          ('discovery', 'hybrid', 'Découverte', 'Discovery'), ('power', 'hybrid', 'Puissance', 'Power'),
          ('break', 'agents', 'Détection de rupture', 'Link-break detection'))
COLUMNS_AGENTS = {'fr': ('Agent', 'Pile', 'Nœuds', 'Décisions', 'Médiane par nœud', 'Action la plus choisie (\\%)', 'Hors du choix initial (\\%)'),
                  'en': ('Agent', 'Stack', 'Nodes', 'Decisions', 'Median per node', 'Most chosen action (\\%)', 'Away from the initial choice (\\%)')}
COLS_AGENTS = cells.xcols(('0.64', '0.80', '1.32', '1.00', '1.24'), 'll')
NOT_TRACED = {'fr': 'non tracé', 'en': 'not traced'}


def num(x, nd, lang):
    return plain(x, nd, lang, thousands=nd == 0)


def mean(arm, metric):
    """The mean over the 60 seeds at GOP 9-3 of an arm, or, for LEARNED, the
    mean of the four learned configurations, frozen (240 simulations)."""
    return round2.learned_mean(metric) if arm == LEARNED else controls.mean(arm, metric)


def write_controls(lang):
    out = [HEAD, cells.setup(lang), '\\setlength{\\tabcolsep}{%s}' % SEP,
           '\\begin{tabularx}{\\linewidth}{%s}' % COLS, '\\toprule',
           ' & '.join('\\textbf{%s}' % h for h in COLUMNS[lang]) + ' \\\\', '\\midrule']
    body = []
    for policy, arm, traced, stack in ARMS:
        row = [num(mean(arm, m), nd, lang) for m, nd in
               (('psnr', 2), ('m1loss', 1), ('loss', 1), ('usable', 1), ('declared', 1))]
        row += [num(mean(traced, m), 0, lang) for m in ('rreq_all', 'rerr')]
        body.append([policy, STACK_NAMES[lang][stack]] + row)
    body = cells.align_rows(body, lang, range(2, 9))
    # the policy written once over its stacks, vertically centered
    after = cells.rules(r[0] for r in body)
    for i, r in enumerate(body):
        policy = r[0]
        n = sum(1 for x in body if x[0] == policy)
        first = i == 0 or body[i - 1][0] != policy
        label = POLICIES[lang][policy]
        r = [('\\multirow[m]{%d}{*}{%s}' % (n, label) if n > 1 else label) if first else ''] + r[1:]
        out.append(' & '.join(r) + ' \\\\')
        if after[i]:
            out.append(after[i])
    out.append('\\end{tabularx}')
    return cells.write(lang, 'revision-controles', out)


def write_agents(lang, trace):
    out = [HEAD_AGENTS, cells.setup(lang),
           '\\begin{tabularx}{\\linewidth}{%s}' % COLS_AGENTS, '\\toprule',
           ' & '.join('\\textbf{%s}' % h for h in COLUMNS_AGENTS[lang]) + ' \\\\', '\\midrule']
    body = []
    for agent, arm, fr, en in AGENTS:
        r = next(x for x in trace if x['arm'] == arm and x['agent'] == agent and x['t'] == '999')
        top = 100.0 * max(float(r['a%d' % a]) for a in range(9)) / float(r['decisions'])
        row = [num(float(r['nodes']), 0, lang), num(float(r['decisions']), 0, lang), num(float(r['median']), 0, lang),
               num(top, 1, lang), num(float(r['changed']), 1, lang) if r['changed'] else NOT_TRACED[lang]]
        body.append([fr if lang == 'fr' else en, STACK_NAMES[lang][arm]] + row)
    body = cells.align_rows(body, lang, range(2, 7))
    for r, after in zip(body, cells.rules(range(len(body)))):
        out += [' & '.join(r) + ' \\\\', after]
    out.append('\\end{tabularx}')
    return cells.write(lang, 'revision-agents', out)


def tables(langs):
    trace = data.read_tsv('agent-trace.tsv')
    out = []
    for lang in langs:
        out += [write_controls(lang), write_agents(lang, trace)]
    return out
