# GOP, "Configurations", "Section" and "Experiment" hold on one line, the
# stacks too but for the series the access-only stack joins (T7), on two, so
# that the table holds on its page. One width unit is 69.0 pt at the full
# length, 525.2 pt, less 3 pt on each side of the seven columns.
PLAN_WIDTHS = ('0.78', '1.08', '1.90', '1.00', '0.74', '1.00', '0.50')
PLAN_SEP = '3pt'
# The series of an experiment, one per line of a nested tabular that spans the
# factor, stacks and GOP columns (no partial rule cuts the row of an
# experiment). Its columns take the widths of
# the columns they sit under: an X column of this table is w/7 of the full
# length less the 14 column separations, and two inner columns stay apart by
# the two separations of the outer table. The series are set apart by this
# space, the experiments by a \midrule; the experiment, its question, counts
# and sections, plain cells of the outer row, are centered on all its series
# (the X columns of the MDPI class are m columns).
SERIES_GAP = '2pt'  # so that the table holds on its page


def series_block(rows):
    """The series of one experiment (factor, stacks, GOP per series) as one
    cell spanning the three columns, a series per line."""
    spec = '@{\\hspace{2\\tabcolsep}}'.join(
        '>{\\centering\\arraybackslash}m{\\dimexpr(\\fulllength-14\\tabcolsep)*%d/700\\relax}' % round(float(w) * 100)
        for w in PLAN_WIDTHS[2:5])
    body = (' \\\\ \\addlinespace[%s]\n' % SERIES_GAP).join(' & '.join(c) for c in rows)
    return '\\multicolumn{3}{c}{\\begin{tabular}[c]{@{}%s@{}}\n%s\n\\end{tabular}}' % (spec, body)


def write_plan(lang, rows):
    t = TEXT[lang]
    out = [HEAD_PLAN, cells.setup(lang), '\\setlength{\\tabcolsep}{%s}' % PLAN_SEP,
           '\\begin{tabularx}{\\fulllength}{%s}'
           % ''.join('>{\\hsize=%s\\hsize\\centering\\arraybackslash}X' % w for w in PLAN_WIDTHS),
           '\\toprule', ' & '.join('\\textbf{%s}' % h for h in t['head']) + ' \\\\', '\\midrule']
    # The two measurements (agents' traces, costs for a node) have no factor of
    # their own: the text of section 2.7 names them; the table lists the
    # experiments E0 to E5 only.
    exps = [e for e in ORDER if e not in MEASURES]
    for i, e in enumerate(exps):
        series = rows[e]
        # the Holm family of each series is said once, in the method (section 2.7)
        q, f = t[e]
        n = sum(r['n'] for r in series.values())
        sims = sum(r['sims'] for r in series.values())
        conf_cell = t['none'] if n == 0 else '%s (%s)' % (num(n, lang), num(sims, lang))
        # the English labels are the French ones without the fr- infix
        sec = ', '.join('\\ref{sec:%sresults-%s}' % ('fr-' if lang == 'fr' else '', s) for s in SECTION[e])
        code = t['measure'] if e in MEASURES else e
        # one line per series, its factor and levels, stacks and GOPs; the
        # experiment, its question, counts and sections written once, centered
        # on its series; no rule between the series of an experiment, a
        # \\midrule between experiments
        per_series = [(f[name] if isinstance(f, dict) else f, stacks_text(r['stacks'], lang), gops_text(r['gops'], lang))
                      for name, r in series.items()]
        middle = ' & '.join(per_series[0]) if len(per_series) == 1 else series_block(per_series)
        out.append(' & '.join((code, q, middle, conf_cell, sec)) + ' \\\\')
        out.append('\\bottomrule' if i == len(exps) - 1 else '\\midrule')
    out.append('\\end{tabularx}')
    return cells.write(lang, 'revision-plan', out)


HEAD_FAMILIES = '% generated by code/analysis/sensors_rl/tables/plan.py (FAMILIES)'
# The header; the notes of the table follow their superscripts.
FAMILY_HEAD = {'fr': ('Expérience', 'Question commune', 'Tests corrigés ensemble', ('Nombre', 'de tests')),
               'en': ('Experiment', 'Common question', 'Tests corrected together', ('Number', 'of tests'))}
FAMILY_NOTES = {'fr': ("«~par~», «~pour~»~: une famille de même taille par élément cité~; variation~: de l'écart de PSNR hybride $-$ "
                       'règles face à la référence.', 'Hors famille (test unique, non corrigé)~: %s.'),
                'en': ('\\emph{for each}: one family of the same size per item; change: of the PSNR difference hybrid $-$ '
                       'rules from the reference.', 'Outside a family (single test, uncorrected): %s.')}
# 8 pt, one printed line per row: the experiment once over its rows, the
# question as wide as its longest cell, the tests in what is left, the counts;
# a rule between two experiments, none between the rows of one.
FAMILY_SEP = '3.5pt'
FAMILY_COLS = cells.FILL + 'cl>{\\raggedright\\arraybackslash}Xc'


def write_families(lang):
    """The families of Holm's correction, by experiment: the experiment
    written once over its rows, each with its question, the tests corrected
    together and their number."""
    first, *head = FAMILY_HEAD[lang]
    head = ['\\textbf{%s}' % first, '\\textbf{%s}' % head[0], '\\textbf{%s}\\textsuperscript{1}' % head[1],
            '\\begin{tabular}[c]{@{}c@{}}\\textbf{%s}\\\\ \\textbf{%s}\\textsuperscript{2}\\end{tabular}' % head[2]]
    out = [HEAD_FAMILIES, '\\footnotesize', '\\setlength{\\tabcolsep}{%s}' % FAMILY_SEP,
           '\\begin{tabularx}{\\fulllength}{%s}' % FAMILY_COLS,
           '\\toprule', ' & '.join(head) + ' \\\\', '\\midrule']
    codes = [f.experiment for f in FAMILIES]
    assert codes == sorted(codes), 'the rows of an experiment are apart'
    for i, (f, after) in enumerate(zip(FAMILIES, cells.rules(codes))):
        n = codes.count(f.experiment)
        code = '' if codes.index(f.experiment) != i else f.experiment if n == 1 else '\\multirow[m]{%d}{*}{%s}' % (n, f.experiment)
        question, tests = (f.fr_question, f.fr) if lang == 'fr' else (f.en_question, f.en)
        out.append(' & '.join((code, question, tests, '%d' % f.size)) + ' \\\\')
        if after:
            out.append(after)
    out.append('\\end{tabularx}')
    return cells.write(lang, 'revision-familles', out)


def write_family_notes(lang):
    """The notes under the families table, as the journal's template sets
    them, after the float's adjustwidth: how many families a row stands for,
    and the single tests, outside the families."""
    several, outside = FAMILY_NOTES[lang]
    return cells.write(lang, 'revision-familles-notes', [
        HEAD_FAMILIES, '{\\footnotesize\\noindent\\textsuperscript{1} %s \\textsuperscript{2} %s\\par}' % (several, outside % SINGLE[lang])])


def report():
    rows = collect()
    for e in ORDER:
        for series, r in rows[e].items():
            fams = ['%d (%s)' % (f.size, f.en) for f in FAMILIES if (series or e) in f.series.split()]
            print('%-6s %-8s %3d configurations, %5d simulations, stacks %s, GOP %s, Holm %s'
                  % (e, series or '-', r['n'], r['sims'], sorted(r['stacks']), sorted(r['gops']),
                     '; '.join(fams) or 'none'))
    print('total studies 10 and 11: %d configurations'
          % sum(r['n'] for e in ORDER if e != 'E0' for r in rows[e].values()))
    print('%d families of Holm\'s correction' % len(FAMILIES))


def tables(langs):
    rows = collect()
    out = []
    for lang in langs:
        out += [write_plan(lang, rows), write_families(lang), write_family_notes(lang)]
    return out
