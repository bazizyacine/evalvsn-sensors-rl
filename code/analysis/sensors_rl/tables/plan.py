def names(path):
    return [l.split()[0] for l in open(path) if l.strip() and not l.startswith('#')]


def conf():
    out = {}
    for l in open(paths.CONF):
        if l.startswith('set_'):
            v = l.split()
            out[v[0]] = {'proto': v[1], 'label': v[2], 'video': v[7], 'sims': int(v[12])}
    return out


def experiment(name):
    """The (experiment, series) of a study-10 or study-11 set, (None, None)
    for a set declared but not yet in the plan, or None outside the plan."""
    for e, series, pat in RULES:
        if re.search(pat, name):
            return e, series
    return None


def stack_of(name):
    if name.startswith('set_AOMDV_GC'):
        return 'pq'
    if T7 and any(re.search(pat, name) for _, _, pat in T7_RULES):
        return ACCESS[0]
    # the access-only stack of the controls of study 11 (E2: the access-only
    # series and the learned configurations), named as the text names it; the
    # ablation's -rules-onlyA-s10 stays an agent alone on the rule stack
    if re.search(r'-rules-onlyA(-(dev|cfg)[1-4])?-s11$', name):
        return ACCESS[0]
    for s in ('rules', 'hybrid', 'agents'):
        if re.search(r'-fire[23]?-%s(-|$)' % s, name):
            return s
    raise SystemExit('no stack in ' + name)


def gop_coef(label):
    """gopCoef of the encoder file ipFiles/<label>.dat (fifth column)."""
    path = os.path.join(paths.IPFILES, label + '.dat')
    rows = [l.split() for l in open(path) if l.strip() and not l.startswith('#')]
    if len(rows) != 1:
        raise SystemExit('%s: one encoder line expected' % path)
    return rows[0][4]


def gop_of(name, c):
    if c['video'] != 'fire_qcif':
        return '9-3'
    coef = gop_coef(c['label'])
    if coef not in GOP:
        raise SystemExit('%s: gopCoef %s outside the three GOPs' % (name, coef))
    return GOP[coef]


def collect():
    """rows[experiment][series] = configurations, simulations, stacks and GOPs."""
    c = conf()
    exp = {e: {} for e in ORDER}
    for n in names(paths.study(paths.STUDY_E0, 'sets.txt')):
        exp['E0'].setdefault(None, []).append(n)
    for study in (paths.STUDY_R1, paths.STUDY_R2):
        for n in names(paths.study(study, 'sets.txt')):
            r = experiment(n)
            if r is None:
                raise SystemExit('set outside the plan: ' + n)
            if r[0] is None:
                continue
            exp[r[0]].setdefault(r[1], []).append(n)
    rows = {}
    for e in ORDER:
        rows[e] = {}
        for series in sorted(exp[e], key=lambda x: -1 if x is None else SERIES_ORDER.index(x)):
            sets = exp[e][series]
            missing = [n for n in sets if n not in c]
            if missing:
                raise SystemExit('%s: not in sets.conf: %s' % (e, missing[0]))
            rows[e][series] = {'n': len(sets), 'sims': sum(c[n]['sims'] for n in sets),
                               'stacks': {stack_of(n) for n in sets},
                               'gops': {gop_of(n, c[n]) for n in sets}}
    # the overheads have no simulation of their own: they are measured on E0 and
    # the traces at GOP 9-3, with the four stacks
    rows['costs'] = {None: {'n': 0, 'sims': 0, 'stacks': {s for s, _, _ in STACKS}, 'gops': {'9-3'}}}
    return rows


def num(n, lang):
    return fixed(n, 0, lang, thousands=True)


def stacks_text(st, lang):
    """The stacks of a series; the access-only stack, the primary comparison,
    first where it joins the four of E0, these unbroken on the next line."""
    t = TEXT[lang]
    four = {s for s, _, _ in STACKS}
    if st >= four:
        return ', '.join(([ACCESS[1 if lang == 'fr' else 2]] if ACCESS[0] in st else []) + [t['all']])
    named = STACKS[:2] + (ACCESS,) + STACKS[2:]
    return ', '.join((fr if lang == 'fr' else en) for s, fr, en in named if s in st)


def gops_text(g, lang):
    return ', '.join(x for x in GOPS if x in g) if g else TEXT[lang]['none']


# Column widths (they sum to 7) and the space between columns: the factor and
# its levels, the longest cells, get the width the short cells of the stacks,
