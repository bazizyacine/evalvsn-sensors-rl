"""The quality table, the quality of the images and the timeliness of the
packets of the main study: one row per stack and GOP, the GOP written once
over its rows, means over the 60 simulations of a stack and a GOP. Beside the
four stacks of the main study, on the same 60 seeds, AOMDV with cross-layer
timers (the tuned series of experiment E1) and
the access-only stack (the rule stack with the channel-access agent alone,
experiment E2: study 10 at GOP 9-3 in revision.tsv, study 11 at 6-6 and 3-9
in round2.tsv). The missed deadlines count the packets received,
the share received in time the packets sent (analysis/quality.py, on_time).
A simulation that received no packet has no delay: AOMDV keeps
58 of its 60 simulations in those columns, and counts the two others at 0 %
received in time (the table's note)."""
from ..analysis import quality as q
from ..analysis import round2
from ..common import data
from ..common.notation import fixed
from . import cells

HEAD = '% generated by code/analysis/sensors_rl/tables/quality.py from data/sensors-rl/article/revision.tsv and round2.tsv'
LABEL = {'pq': ('AOMDV', 'AOMDV'), 'pq-tuned': ('AOMDV aux temporisations inter-couches', 'AOMDV with cross-layer timers'),
         'rules': ('Règles', 'Rules'), 'access': ('Accès seul', 'Access only'), 'agents': ('Agents', 'Agents'),
         'hybrid': ('Hybride', 'Hybrid')}
# the rows of a GOP
ARMS = ('pq', 'pq-tuned', 'rules', 'access', 'agents', 'hybrid')
# the measures of the columns and their decimals (analysis/quality.py)
METRICS = (('psnr', 2), ('usable', 1), ('delay_mean', 0), ('late', 2), ('on_time', 1))
# the base of each share, in parentheses, on the second line of its header
COLUMNS = {'fr': ('GOP', 'Pile', 'PSNR (dB)', cells.IMAGES, 'Délai moyen (ms)', 'Échéance manquée (\\%~des~reçus)',
                  'Reçus à temps (\\%~des~envoyés)'),
           'en': ('GOP', 'Stack', 'PSNR (dB)', cells.IMAGES, 'Mean delay (ms)', 'Missed deadline (\\%~of~received)',
                  'Received in time (\\%~of~sent)')}


def arm_at(arm, split):
    """The arm of a row at a GOP: the access-only stack's is study 10's at
    GOP 9-3 and study 11's at the two others (analysis/round2.py)."""
    return round2.access_only(split) if arm == 'access' else arm


# The GOP centered as in the comparative tables, the stack a left-aligned
# label on one line; the six X columns share the free width so that every
# header holds on two lines at most.
SEP = '4pt'
COLS = cells.xcols(('0.50',), fill=True) + 'l' + cells.xcols(('0.66', '0.92', '0.86', '1.53', '1.53'))


def write(lang):
    out = [HEAD, cells.setup(lang), '\\setlength{\\tabcolsep}{%s}' % SEP,
           '\\begin{tabularx}{\\linewidth}{%s}' % COLS, '\\toprule',
           ' & '.join('\\textbf{%s}' % h for h in COLUMNS[lang]) + ' \\\\', '\\midrule']
    body = cells.align_rows([[fixed(q.mean(arm_at(arm, split), m, split), nd, lang, thousands=nd == 0)
                              for m, nd in METRICS]
                             for split in data.SPLITS for arm in ARMS], lang)
    after = iter(cells.rules(split for split in data.SPLITS for _ in ARMS))
    for i, split in enumerate(data.SPLITS):
        for k, arm in enumerate(ARMS):
            first = '\\multirow[m]{%d}{*}{%s}' % (len(ARMS), data.GOP[split]) if k == 0 else ''
            label = LABEL[arm][0 if lang == 'fr' else 1] + ('\\textsuperscript{1}' if arm == 'pq' else '')
            out.append(' & '.join([first, label] + body[i * len(ARMS) + k]) + ' \\\\')
            rule = next(after)
            if rule:
                out.append(rule)
    out.append('\\end{tabularx}')
    return cells.write(lang, 'revision-qualite', out)


def tables(langs):
    return [write(lang) for lang in langs]
