"""The equal-rate and quality-coefficient tables, video coding (experiment
E4), means over the 60 seeds, a cell without all 60 printing as a dash: the
equal-rate series (one row per GOP and alarm period, the rules and hybrid
stacks side by side under each measure) and the coefficient 0.1 series (one
row per stack at GOP 9-3 and T = 9 s, the coefficients 0.01 and 0.1 side by
side). The second round adds the access-only stack, on the same 60 seeds: its
PSNR in the equal-rate table, its row in the coefficient table (tranche T7 of
study 11, analysis/access_robustness.py)."""
from ..analysis import access_robustness as ar
from ..analysis import coding
from ..common import data
from ..common.notation import plain
from . import cells

HEAD = '% generated by code/analysis/sensors_rl/tables/coding.py from data/sensors-rl/article/revision.tsv and round2.tsv'
ROWS = (('3M9D', 'p9'), ('3M9D', 'p9r65'), ('6M6D', 'p9'), ('6M6D', 'p9r32'), ('9M3D', 'p9'))
PAIR = (('rules', 'Règles', 'Rules'), ('hybrid', 'Hybride', 'Hybrid'))
ACCESS = ('access', 'Accès seul', 'Access only')
STACKS = (('pq', 'AOMDV', 'AOMDV'), ('rules', 'Règles', 'Rules'), ACCESS, ('agents', 'Agents', 'Agents'),
          ('hybrid', 'Hybride', 'Hybrid'))
# the column headers name the coefficient of each column
COEF = (('', 'à 0{,}01', 'at 0.01'), ('-q01', 'à 0{,}1', 'at 0.1'))
METRICS = (('psnr', 2), ('m1loss', 1), ('loss', 1), ('usable', 1))
MEASURE = {'fr': ('PSNR (dB)', 'Perte M1 (\\%)', 'Perte (\\%)', cells.IMAGES),
           'en': ('PSNR (dB)', 'M1 loss (\\%)', 'Loss (\\%)', cells.IMAGES)}
RATE = {'fr': 'Débit moyen (paquets/s)', 'en': 'Mean rate (packets/s)'}
STACK = {'fr': 'Pile', 'en': 'Stack'}
# Shares of the free width (tabularx): in the equal-rate table, 9 pt with a
# column padding of 3 pt, each "Hybride" on one line and the mean rate on two;
# in the coefficient table, the mean rate's header on one line over its two
# columns.
VOLUME_SEP = '3pt'
W_VOLUME = cells.xcols(['%.2f' % w for w in (0.70, 0.72, 1.52) + (0.96, 0.86, 1.12) + (0.93, 1.11) * 3], fill=True)
W_COEF = cells.xcols(['%.2f' % w for w in (1.48,) * 2 + (0.88,) * 8], 'l', fill=True)


def mean(stack, split, period, metric, suffix=''):
    """The mean of a cell: the access-only stack's from its arm at the level
    (access_robustness), the others from revision.tsv."""
    if stack != 'access':
        return coding.mean(stack + suffix, split, period, metric)
    return ar.mean('access', ar.Level(period, suffix.lstrip('-') or None, split, period, '40'), metric)


def header(first, groups, subs):
    """Two header rows: each group over its columns (subs, one tuple of
    column names per group), then every column named, the single columns on
    the second row."""
    top, rules, n = [''] * len(first), [], len(first)
    for g, names in zip(groups, subs):
        top.append('\\multicolumn{%d}{c}{\\textbf{%s}}' % (len(names), g))
        rules.append('\\cmidrule(lr){%d-%d}' % (n + 1, n + len(names)))
        n += len(names)
    low = ['\\textbf{%s}' % h for h in first] + ['\\textbf{%s}' % s for names in subs for s in names]
    return [' & '.join(top) + ' \\\\', ''.join(rules), ' & '.join(low) + ' \\\\', '\\midrule']


def write_volume(lang):
    k = 1 if lang == 'fr' else 2
    out = [HEAD, cells.setup(lang), '\\small', '\\setlength{\\tabcolsep}{%s}' % VOLUME_SEP,
           '\\begin{tabularx}{\\linewidth}{%s}' % W_VOLUME, '\\toprule']
    # the access-only stack under the PSNR alone
    stacks = [(PAIR[0], ACCESS, PAIR[1]) if m == 'psnr' else PAIR for m, _ in METRICS]
    out += header(('GOP', '$T$ (s)', RATE[lang]), MEASURE[lang], [tuple(s[k] for s in names) for names in stacks])
    splits = [s for s, _ in ROWS]
    body = []
    for split, period in ROWS:
        T = coding.PERIOD[period]
        row = [plain(T, 2 if T != 9.0 else 0, lang), plain(coding.rate(coding.PACKETS[split], period), 1, lang)]
        row += [plain(mean(s[0], split, period, m), nd, lang) for (m, nd), names in zip(METRICS, stacks) for s in names]
        body.append(row)
    body = cells.align_rows(body, lang)
    after = cells.rules(splits)
    for i, (split, period) in enumerate(ROWS):
        # the GOP named once over its rows, vertically centered
        span = splits.count(split)
        stub = data.GOP[split] if span == 1 else ('\\multirow[m]{%d}{*}{%s}' % (span, data.GOP[split]) if splits.index(split) == i else '')
        out.append(' & '.join([stub] + body[i]) + ' \\\\')
        if after[i]:
            out.append(after[i])
    out.append('\\end{tabularx}')
    return cells.write(lang, 'revision-volume', out)


def write_coefficient(lang):
    k = 1 if lang == 'fr' else 2
    out = [HEAD, cells.setup(lang),
           '\\begin{tabularx}{\\linewidth}{%s}' % W_COEF, '\\toprule']
    out += header((STACK[lang],), (RATE[lang],) + MEASURE[lang], [tuple(c[k] for c in COEF)] * (1 + len(METRICS)))
    body = []
    for arm, fr, en in STACKS:
        row = [fr if lang == 'fr' else en]
        row += [plain(coding.rate(coding.PACKETS_Q01 if suf else coding.PACKETS['9M3D'], 'p9'), 1, lang) for suf, _, _ in COEF]
        row += [plain(mean(arm, '9M3D', 'p9', m, suf), nd, lang) for m, nd in METRICS for suf, _, _ in COEF]
        body.append(row)
    body = cells.align_rows(body, lang, range(1, 1 + 2 * (1 + len(METRICS))))
    for r, after in zip(body, cells.rules(range(len(body)))):
        out += [' & '.join(r) + ' \\\\', after]
    out.append('\\end{tabularx}')
    return cells.write(lang, 'revision-qualite-coef', out)


def tables(langs):
    out = []
    for lang in langs:
        out += [write_volume(lang), write_coefficient(lang)]
    return out
