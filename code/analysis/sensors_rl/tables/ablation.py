"""The single-agent ablations (experiment E2): one row per agent, the mean of
the per-seed differences between the stack with the agent and the same stack
with its rule, alone on the rule stack and in the hybrid stack; each PSNR
difference is followed by its 95 % interval on one line (cells.intervals),
its p, Holm's within each family, in a column of its own (the link-break
agent in the hybrid stack, agents - hybrid, keeps the p of its family of E0,
Holm over the three GOPs). A cell the 60 seeds do not all back prints as a
dash."""
from ..analysis import ablation
from ..common.notation import pval, signed
from . import cells

HEAD = '% generated by code/analysis/sensors_rl/tables/ablation.py from data/sensors-rl/article/revision.tsv'
AGENTS = (('P', 'Chemin', 'Path'), ('C', 'Congestion', 'Congestion'), ('A', 'Accès au canal', 'Channel access'),
          ('E', 'Rejet anticipé', 'Early discard'), ('D', 'Découverte', 'Discovery'), ('T', 'Puissance', 'Power'),
          ('B', 'Détection de rupture', 'Link-break detection'))
GROUPS = {'fr': ('Seul sur la pile à règles', 'Dans la pile hybride'),
          'en': ('Alone on the rule stack', 'In the hybrid stack')}
COLUMNS = {'fr': ('Agent', 'PSNR (dB)', '$p$', 'Perte M1 (points)', 'Décl.'),
           'en': ('Agent', 'PSNR (dB)', '$p$', 'M1 loss (points)', 'Decl.')}
# 8 pt and 3 pt between columns: the gap with its interval is on one line.
# Unequal widths, summing to the four columns of a group, so that the bold
# headers hold on two lines.
SEP = '3pt'
GROUP = cells.xcols(('1.68', '0.74', '0.88', '0.70'))


def field(fam, x, name):
    """The mean or Holm's p of agent x in a family, None when absent."""
    return getattr(fam[x], name) if x in fam else None


def write(lang, fams):
    g1, g2 = GROUPS[lang]
    h = COLUMNS[lang]
    out = [HEAD, cells.setup(lang), '\\footnotesize', '\\setlength{\\tabcolsep}{%s}' % SEP,
           '\\begin{tabularx}{\\linewidth}{%sl%s}' % (cells.FILL, GROUP * 2), '\\toprule',
           ' & \\multicolumn{4}{c}{\\textbf{%s}} & \\multicolumn{4}{c}{\\textbf{%s}} \\\\' % (g1, g2),
           '\\cmidrule(lr){2-5}\\cmidrule(lr){6-9}',
           ' & '.join('\\textbf{%s}' % x for x in (h[0],) + h[1:] * 2) + ' \\\\', '\\midrule']
    gaps = [cells.intervals([fams['psnr'][side].get(x) for x, _, _ in AGENTS], 2, lang) for side in (0, 1)]
    rows = []
    for i, (x, fr, en) in enumerate(AGENTS):
        row = []
        for side in (0, 1):
            psnr, m1, dec = (fams[m][side] for m in ('psnr', 'm1loss', 'declared'))
            row += [gaps[side][i], pval(field(psnr, x, 'holm'), lang),
                    signed(field(m1, x, 'mean'), 1, lang), signed(field(dec, x, 'mean'), 1, lang)]
        rows.append([fr if lang == 'fr' else en] + row)
    rows = cells.align_rows(rows, lang, (2, 3, 4, 6, 7, 8), pcols=(2, 6))
    for r, after in zip(rows, cells.rules(range(len(rows)))):
        out += [' & '.join(r) + ' \\\\', after]
    out.append('\\end{tabularx}')
    return cells.write(lang, 'revision-ablation', out)


def tables(langs):
    fams = {m: ablation.effects(m) for m in ('psnr', 'm1loss', 'declared')}
    return [write(lang, fams) for lang in langs]
