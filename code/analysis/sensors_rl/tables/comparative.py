"""The tables of the main study (study 09): the PSNR of the stacks per fire
and GOP with the half-width of the 95 % interval of each mean
(comparatif-psnr), the paired differences between the cross-layer stacks per
cell, each with its 95 % interval and, for the comparisons of the main study,
its p, Holm over the nine cells of each comparison (comparatif-tests; the two
comparisons of the access-only stack are tested at the three GOPs, not per
cell), and the repeated-measures ANOVA of the three
cross-layer stacks with the Greenhouse-Geisser correction of each within-seed
term and the 95 % interval of each partial eta squared, in brackets after it
(comparatif-anova).

The four stacks of the main study come from comparative.tsv. The second round
adds, on the same 60 seeds, AOMDV with cross-layer timers (the tuned series
of experiment E1, revision.tsv) and the access-only stack (the
rule stack with the channel-access agent alone, experiment E2: study 10 at
GOP 9-3 in revision.tsv, study 11 at 6-6 and 3-9 in round2.tsv)."""
from ..analysis import comparative as comp
from ..analysis import quality, round2
from ..common import data, stats
from ..common.notation import fixed, ptext, pval
from . import cells

HEAD = '% generated by code/analysis/sensors_rl/tables/comparative.py from data/sensors-rl/article/comparative.tsv'
HEAD_STACKS = HEAD + ', revision.tsv and round2.tsv'
SPLITS = tuple((s, data.GOP[s]) for s in data.SPLITS)
WORDS = {
    'fr': {'stacks': (('aomdv', 'AOMDV'), ('tuned', 'AOMDV aux temporisations inter-couches'), ('rules', 'Règles'),
                      ('access', 'Accès seul'), ('agents', 'Agents'), ('hybrid', 'Hybride')),
           'pairs': (('access', 'rules', 'Accès seul $-$ Règles'), ('hybrid', 'access', 'Hybride $-$ Accès seul'),
                     ('hybrid', 'rules', 'Hybride $-$ Règles'), ('agents', 'rules', 'Agents $-$ Règles'),
                     ('hybrid', 'agents', 'Hybride $-$ Agents')),
           'terms': {'stack': 'Pile', 'fire': 'Feu', 'split': 'GOP'},
           'gap': 'Écart de PSNR (dB)',
           'fire': 'Feu', 'factor': 'Facteur', 'df': 'Degrés de liberté (terme, erreur)',
           'gg': 'Facteur de Greenhouse-Geisser', 'pgg': '$p$ corrigé', 'eta': '$\\eta^2$ partiel'},
    'en': {'stacks': (('aomdv', 'AOMDV'), ('tuned', 'AOMDV with cross-layer timers'), ('rules', 'Rules'),
                      ('access', 'Access only'), ('agents', 'Agents'), ('hybrid', 'Hybrid')),
           'pairs': (('access', 'rules', 'Access only $-$ Rules'), ('hybrid', 'access', 'Hybrid $-$ Access only'),
                     ('hybrid', 'rules', 'Hybrid $-$ Rules'), ('agents', 'rules', 'Agents $-$ Rules'),
                     ('hybrid', 'agents', 'Hybrid $-$ Agents')),
           'terms': {'stack': 'Stack', 'fire': 'Fire', 'split': 'GOP'},
           'gap': 'PSNR difference (dB)',
           'fire': 'Fire', 'factor': 'Factor', 'df': 'Degrees of freedom (term, error)',
           'gg': 'Greenhouse--Geisser factor', 'pgg': 'Corrected $p$', 'eta': 'Partial $\\eta^2$'},
}
# Fire and GOP centered as the codes they are, then the six stacks; AOMDV with
# cross-layer timers takes the width of "temporisations".
PSNR_SEP = '4pt'
PSNR_COLS = cells.xcols(('0.42', '0.56', '1.10', '1.42', '1.10', '1.10', '1.10', '1.20'), fill=True)
# Fire, GOP, then, for each of the five pairs, the PSNR gap with its interval
# on one line and, but for the access-only stack's two pairs, its p under it.
TESTS_SEP = '3pt'
TESTS_COLS = cells.xcols(('0.40', '0.45') + ('1.23',) * 5, fill=True)
# The factor is a label, left-aligned; the Greenhouse-Geisser factor's
# header holds on two lines and the partial eta squared with its interval on
# one, hence the narrower space between the columns.
ANOVA_SEP = '4pt'
ANOVA_COLS = cells.xcols(('1.14', '0.50', '0.70', '1.53', '0.77', '1.36'), 'l', fill=True)


def first(fire, k, lines=1):
    """The first column as the MDPI template writes it: the value once,
    vertically centered on the rows it spans, of the given lines each."""
    return '\\multirow[m]{%d}{*}{%s}' % (len(SPLITS) * lines, fire) if k == 0 else ''


def rules():
    """No rule between the GOPs of a fire, a \\midrule between two fires."""
    return cells.rules(fire for fire in data.FIRES for _ in SPLITS)


def num(x, nd, lang):
    return fixed(x, nd, lang, minus=True)


def cell_values(psnr, fire, split, stack):
    """{realisation: PSNR} of a stack in a cell: the main study's four stacks
    from comparative.tsv (psnr, comp.cells), the two others from their arm."""
    if stack in ('tuned', 'access'):
        arm = 'pq-tuned' if stack == 'tuned' else round2.access_only(split)
        return {k[1]: v for k, v in quality.values(arm, 'psnr', split).items() if k[0] == fire}
    return psnr.get((fire, split, stack))


def cell_tests(psnr, a, b):
    """{(fire, split): Estimate of a - b}, Holm over the nine cells, but for
    the access-only stack's two comparisons, without a test there
    (round2.access_cells)."""
    if 'access' in (a, b):
        return round2.access_cells('%s - %s' % (a, b))
    return comp.paired_cells(psnr, a, b)


def write(lang, rows):
    W = WORDS[lang]
    stacks, pairs = W['stacks'], W['pairs']
    psnr = comp.cells(rows, 'psnr')
    written = []

    # comparatif-psnr: the quantity over the stacks, as in the load and scenario tables
    out = [HEAD_STACKS, cells.setup(lang), '\\setlength{\\tabcolsep}{%s}' % PSNR_SEP,
           '\\begin{tabularx}{\\linewidth}{%s}' % PSNR_COLS, '\\toprule',
           ' & & \\multicolumn{%d}{c}{\\textbf{PSNR (dB)}} \\\\' % len(stacks),
           '\\cmidrule(lr){3-%d}' % (2 + len(stacks)),
           '\\textbf{%s} & \\textbf{GOP} & ' % W['fire'] + ' & '.join('\\textbf{%s}' % lab for _, lab in stacks) + ' \\\\']
    keys = [(fire, sp) for fire in data.FIRES for sp, _ in SPLITS]
    mu, hw = [], []
    for fire, sp in keys:
        vals = [cell_values(psnr, fire, sp, st) for st, _ in stacks]
        mu.append([num(stats.mean(v.values()), 2, lang) if v else '--' for v in vals])
        hw.append([num(comp.half_width(v.values()), 2, lang) if v else '' for v in vals])
    mu, hw = cells.align_rows(mu, lang), cells.align_rows(hw, lang)
    out.append('\\midrule')
    for n, ((fire, sp), after) in enumerate(zip(keys, rules())):
        k = [s for s, _ in SPLITS].index(sp)
        txt = [m if not h else '\\mbox{%s $\\pm$ %s}' % (m, h) for m, h in zip(mu[n], hw[n])]
        out.append('%s & %s & %s \\\\' % (first(fire, k), SPLITS[k][1], ' & '.join(txt)))
        if after:
            out.append(after)
    out.append('\\end{tabularx}')
    written.append(cells.write(lang, 'comparatif-psnr', out))

    # comparatif-tests: the paired differences, the interval after the gap and
    # p under it, Holm over the nine cells of each comparison of the main study
    out = [HEAD_STACKS, cells.setup(lang), '\\footnotesize', '\\setlength{\\tabcolsep}{%s}' % TESTS_SEP,
           '\\begin{tabularx}{\\linewidth}{%s}' % TESTS_COLS, '\\toprule',
           ' & & \\multicolumn{%d}{c}{\\textbf{%s}} \\\\' % (len(pairs), W['gap']),
           '\\cmidrule(lr){3-%d}' % (2 + len(pairs)),
           '\\textbf{%s} & \\textbf{GOP} & ' % W['fire'] + ' & '.join('\\textbf{%s}' % lab for _, _, lab in pairs) + ' \\\\',
           '\\midrule']
    columns = []
    for a, b, _ in pairs:
        tests = cell_tests(psnr, a, b)
        gaps = cells.intervals([tests[k] for k in keys], 2, lang)
        columns.append([g if tests[k].holm is None else '%s\\newline %s' % (g, ptext(tests[k].holm, lang))
                        for g, k in zip(gaps, keys)])
    after = rules()
    for n, (fire, sp) in enumerate(keys):
        k = [s for s, _ in SPLITS].index(sp)
        out.append('%s & %s & %s \\\\' % (first(fire, k, 2), SPLITS[k][1], ' & '.join(c[n] for c in columns)))
        out.append(after[n] or '\\addlinespace[2pt]')
    out.append('\\end{tabularx}')
    written.append(cells.write(lang, 'comparatif-tests', out))

    # comparatif-anova: the repeated-measures ANOVA of the three cross-layer stacks,
    # each within-seed term with the Greenhouse-Geisser factor of its stratum
    # and its corrected p; the fire, between the seeds, has neither; each
    # partial eta2 with its 95 % interval
    if all((fi, sp, st) in psnr for fi in data.FIRES for sp, _ in SPLITS for st in comp.STACKS):
        res = comp.anova(rows)
        out = [HEAD, cells.setup(lang), '\\setlength{\\tabcolsep}{%s}' % ANOVA_SEP,
               '\\begin{tabularx}{\\linewidth}{%s}' % ANOVA_COLS, '\\toprule',
               ' & '.join('\\textbf{%s}' % h for h in (W['factor'], W['df'], '$F$', '$p$', W['gg'], W['pgg'], W['eta']))
               + ' \\\\']
        # F, p, the factor, the corrected p and the partial eta2 aligned on the
        # decimal marker; the pair of degrees of freedom stays a centered pair
        eta = cells.intervals(list(comp.effect_sizes(rows).values()), 2, lang, plus=False)
        body = [['%d, %d' % (t[1], t[2]), num(t[3], 1, lang), pval(t[4], lang, half=False),
                 num(t[6], 2, lang) if t[6] is not None else '--', pval(t[7], lang, half=False) if t[6] is not None else '--', e]
                for t, e in zip(res, eta)]
        body = cells.align_rows(body, lang, range(1, 5), pcols=(2, 4))
        for (term, *_), terms in zip(res, body):
            name = ' $\\times$ '.join(W['terms'][t.strip()] for t in term.split(' x '))
            out += ['\\midrule', ' & '.join((name,) + tuple(terms)) + ' \\\\']
        out += ['\\bottomrule', '\\end{tabularx}']
        written.append(cells.write(lang, 'comparatif-anova', out))
    return written


def tables(langs):
    rows = comp.rows()
    return [p for lang in langs for p in write(lang, rows)]
